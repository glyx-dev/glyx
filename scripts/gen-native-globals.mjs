#!/usr/bin/env node
// Writes js/glyx-native.d.ts: a `declare var __glyx_x: any;` for every native binding
// (`__glyx_*`) the packages' sources mention. These are the JavaScript/Rust boundary, injected
// by the runtime; declaring them lets the packages type-check. They are `any` for now:
// to type one properly, declare it by hand in js/glyx-native.hand.d.ts (names there are skipped here).
//
//   node scripts/gen-native-globals.mjs           write js/glyx-native.d.ts
//   node scripts/gen-native-globals.mjs --check   fail if it is out of date
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER =
  '// Generated by scripts/gen-native-globals.mjs from the packages\' sources. Do not edit:\n' +
  '// run `node scripts/gen-native-globals.mjs`. To give a binding a real type, declare it in\n' +
  '// glyx-native.hand.d.ts instead (it is skipped here).\n\n';

export function nativeNames(text) {
  return new Set(text.match(/\b__glyx_[A-Za-z0-9_]+\b/g) ?? []);
}

export function render(names) {
  return HEADER + [...names].sort().map((n) => `declare var ${n}: any;`).join('\n') + '\n';
}

function sources(dir, out = []) {
  for (const f of readdirSync(dir)) {
    if (f === 'node_modules' || f === 'types') continue;
    const p = join(dir, f);
    if (statSync(p).isDirectory()) sources(p, out);
    else if (/\.(m?[jt]sx?)$/.test(f) && !f.endsWith('.d.ts')) out.push(p);
  }
  return out;
}

function main() {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const js = join(root, 'js');
  const names = new Set();
  for (const file of sources(join(js, 'packages', '@glyx'))) for (const n of nativeNames(readFileSync(file, 'utf8'))) names.add(n);
  const handFile = join(js, 'glyx-native.hand.d.ts');
  if (existsSync(handFile)) for (const n of nativeNames(readFileSync(handFile, 'utf8'))) names.delete(n);
  const next = render(names);
  const target = join(js, 'glyx-native.d.ts');
  const prev = existsSync(target) ? readFileSync(target, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (prev !== next) { console.error('js/glyx-native.d.ts is out of date. Run `node scripts/gen-native-globals.mjs`.'); process.exit(1); }
    console.log('js/glyx-native.d.ts is up to date.');
  } else if (prev !== next) {
    writeFileSync(target, next);
    console.log(`Wrote js/glyx-native.d.ts (${names.size} bindings).`);
  } else {
    console.log('js/glyx-native.d.ts already up to date.');
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
